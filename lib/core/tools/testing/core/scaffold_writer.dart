// ignore_for_file: avoid_print

/// Shared file-writing policy for every generator: never silently clobber, keep
/// a marker for regeneration, and support `--dry-run`.
library;

import 'dart:io';

const generatedMarker = '// GENERATED by lib/core/tools/testing — do not edit by hand.';
const regenerateHint = '// Re-run: dart run lib/core/tools/testing/test_scaffold.dart <command>';

enum WriteAction { created, skipped, overwritten, wouldCreate }

class WriteOutcome {
  WriteOutcome({
    required this.path,
    required this.action,
    this.reason,
  });

  final String path;
  final WriteAction action;
  final String? reason;

  bool get isNew => action == WriteAction.created || action == WriteAction.wouldCreate;

  String get icon => switch (action) {
        WriteAction.created => '✅',
        WriteAction.wouldCreate => '💡',
        WriteAction.overwritten => '♻️ ',
        WriteAction.skipped => '⏭️ ',
      };

  @override
  String toString() =>
      '$icon $path${reason == null ? '' : '  (${reason!})'}';
}

class ScaffoldWriter {
  ScaffoldWriter({this.dryRun = false, this.force = false});

  final bool dryRun;
  final bool force;

  final List<WriteOutcome> outcomes = [];

  int get createdCount => outcomes.where((o) => o.action == WriteAction.created).length;
  int get wouldCreateCount => outcomes.where((o) => o.action == WriteAction.wouldCreate).length;
  int get skippedCount => outcomes.where((o) => o.action == WriteAction.skipped).length;
  int get overwrittenCount => outcomes.where((o) => o.action == WriteAction.overwritten).length;

  /// Writes [content] to [path].
  ///
  /// When the file exists and still carries [generatedMarker] it is treated as
  /// ours and refreshed. A hand-edited file is never touched unless [force] is
  /// set, and [force] keeps a `.bak` so nothing is lost.
  WriteOutcome write(String path, String content) {
    final file = File(path);
    final exists = file.existsSync();

    if (exists && !force) {
      final current = file.readAsStringSync();
      final ours = current.contains(generatedMarker);
      if (!ours) {
        return _record(WriteOutcome(
          path: path,
          action: WriteAction.skipped,
          reason: 'hand-edited (use --force to overwrite)',
        ));
      }
      // Preserve anything the developer appended below the marker.
      final preserved = _tail(current);
      final next = preserved == null ? content : '$content\n$preserved';
      if (next == current) {
        return _record(WriteOutcome(path: path, action: WriteAction.skipped, reason: 'unchanged'));
      }
      if (dryRun) {
        return _record(WriteOutcome(path: path, action: WriteAction.wouldCreate, reason: 'update'));
      }
      file.writeAsStringSync(next);
      return _record(WriteOutcome(path: path, action: WriteAction.overwritten));
    }

    if (dryRun) {
      return _record(WriteOutcome(path: path, action: WriteAction.wouldCreate));
    }

    file.parent.createSync(recursive: true);
    if (exists) {
      file.copySync('$path.bak');
    }
    file.writeAsStringSync(content);
    return _record(WriteOutcome(
      path: path,
      action: WriteAction.created,
      reason: exists ? 'backup at $path.bak' : null,
    ));
  }

  /// Section the developer may hand-edit; everything after it is preserved.
  static const tailMarker = '// ─── custom ───';

  String? _tail(String content) {
    final idx = content.indexOf(tailMarker);
    if (idx == -1) return null;
    final tail = content.substring(idx).trimRight();
    return tail == tailMarker ? null : tail;
  }

  WriteOutcome _record(WriteOutcome o) {
    outcomes.add(o);
    return o;
  }

  void printSummary() {
    if (outcomes.isEmpty) return;
    print('');
    for (final o in outcomes) {
      print('   ${o.path.replaceAll(r'\', '/')}  ${o.reason ?? ''}');
    }
    print('');
    if (dryRun) {
      print('💡 Dry run — nothing written. Re-run without --dry-run to apply.');
    } else {
      print('📊 created: $createdCount  updated: $overwrittenCount  skipped: $skippedCount');
    }
  }
}
